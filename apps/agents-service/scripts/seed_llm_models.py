def main():
    print("Seeding LLM models...")

    app = create_app()

    with app.app_context():
        for model_data in llm_models:
            existing = (
                LLMModel.query.filter_by(name=model_data["name"]).first()
                or LLMModel.query.filter_by(
                    provider=model_data["provider"], model_id=model_data["model_id"]
                ).first()
            )

            if not existing:
                db.session.add(LLMModel(**model_data))
                db.session.flush()
                print(f"Created: {model_data['name']}")
            else:
                updated = False
                for field in UPDATABLE_FIELDS:
                    if getattr(existing, field) != model_data[field]:
                        setattr(existing, field, model_data[field])
                        updated = True
                print(f"{'Updated' if updated else 'Exists'}: {model_data['name']}")

        db.session.commit()
        print("Done.")


if __name__ == "__main__":
    main()
